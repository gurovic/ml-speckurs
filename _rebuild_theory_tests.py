def img_sigmoid_threshold():
    z = np.linspace(-6, 6, 300)
    s = 1 / (1 + np.exp(-z))
    fig, ax = plt.subplots(figsize=(5.8, 3.8))
    ax.plot(z, s, lw=2, label=r"$\sigma(z)$")
    ax.axhline(0.5, color="gray", ls="--", label="порог 0.5")
    ax.axvline(0, color="gray", ls=":", alpha=0.8)
    ax.fill_between(z, 0.5, s, where=(s >= 0.5), alpha=0.15, color="#d62728", label="класс 1 при пороге 0.5")
    ax.fill_between(z, s, 0.5, where=(s < 0.5), alpha=0.15, color="#1f77b4", label="класс 0 при пороге 0.5")
    ax.set_xlabel("z (логит)")
    ax.set_ylabel("вероятность")
    ax.set_title("Сигмоида и порог")
    ax.legend(fontsize=8, loc="lower right")
    ax.grid(True, alpha=0.3)
    ax.set_ylim(-0.05, 1.05)
    return fig_b64(fig)


def img_confusion():
    # TN FP / FN TP
    mat = np.array([[80, 20], [30, 70]])
    fig, ax = plt.subplots(figsize=(4.6, 4.0))
    im = ax.imshow(mat, cmap="Blues")
    ax.set_xticks([0, 1], ["прогноз 0", "прогноз 1"])
    ax.set_yticks([0, 1], ["факт 0", "факт 1"])
    for i in range(2):
        for j in range(2):
            labels = [["TN", "FP"], ["FN", "TP"]]
            ax.text(j, i, f"{labels[i][j]}\n{mat[i, j]}", ha="center", va="center", fontsize=13)
    ax.set_title("Матрица ошибок")
    fig.colorbar(im, ax=ax, fraction=0.046)
    fig.tight_layout()
    return fig_b64(fig)


def img_validation_curve_overfit():
    depth = np.arange(1, 11)
    train = 0.55 + 0.045 * depth
    train = np.clip(train, 0, 0.99)
    val = 0.55 + 0.06 * depth - 0.007 * depth ** 2
    fig, ax = plt.subplots(figsize=(5.6, 3.8))
    ax.plot(depth, train, "o-", label="train")
    ax.plot(depth, val, "s-", label="validation")
    ax.set_xlabel("max_depth")
    ax.set_ylabel("качество (выше — лучше)")
    ax.set_title("Validation curve")
    ax.legend()
    ax.grid(True, alpha=0.3)
    return fig_b64(fig)


