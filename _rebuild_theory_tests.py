def img_boosting_loss_curve():
    n = np.arange(1, 81)
    train = 1.2 * np.exp(-0.045 * n) + 0.05
    val = 1.15 * np.exp(-0.04 * n) + 0.08 + 0.004 * np.maximum(0, n - 35)
    fig, ax = plt.subplots(figsize=(5.8, 3.8))
    ax.plot(n, train, label="train loss")
    ax.plot(n, val, label="validation loss")
    ax.axvline(35, color="gray", ls="--", label="примерно начало роста val")
    ax.set_xlabel("число деревьев")
    ax.set_ylabel("ошибка (ниже — лучше)")
    ax.set_title("Ошибка бустинга при росте числа деревьев")
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)
    return fig_b64(fig)


