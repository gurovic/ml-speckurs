def img_scale_dominance():
    fig, axes = plt.subplots(1, 2, figsize=(8.5, 3.6))
    # raw: income dominates → horizontal separation meaningless
    pts = np.array([[30, 50000], [40, 51000], [35, 80000]])
    labels = ["P", "Q", "R"]
    axes[0].scatter(pts[:, 0], pts[:, 1], s=80)
    for (x, y), t in zip(pts, labels):
        axes[0].text(x + 0.3, y + 400, t)
    axes[0].plot([30, 40], [50000, 51000], "k--", alpha=0.5)
    axes[0].set_title("Без масштабирования")
    axes[0].set_xlabel("возраст")
    axes[0].set_ylabel("доход")
    axes[0].grid(True, alpha=0.3)
    # scaled
    mins = np.array([20.0, 40000.0])
    maxs = np.array([60.0, 90000.0])
    s = (pts - mins) / (maxs - mins)
    axes[1].scatter(s[:, 0], s[:, 1], s=80)
    for (x, y), t in zip(s, labels):
        axes[1].text(x + 0.02, y + 0.02, t)
    axes[1].set_title("После min-max в [0, 1]")
    axes[1].set_xlabel("возраст (scaled)")
    axes[1].set_ylabel("доход (scaled)")
    axes[1].grid(True, alpha=0.3)
    fig.suptitle("Как масштаб меняет геометрию для kNN", y=1.02)
    fig.tight_layout()
    return fig_b64(fig)


